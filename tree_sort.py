""" 
МОДУЛЬ СОРТИРОВКИ ДЕРЕВОМ (Tree Sort) 
Рекурсивная реализация 
""" 
 
def tree_sort(arr): 
    """ 
    Сортировка деревом (упрощённая рекурсивная версия) 
 
    Принцип работы: 
    1. Берём первый элемент как корень. 
    2. Делим остальные элементы на два массива: 
       - left  (меньше корня) 
       - right (больше или равны корню) 
    3. Рекурсивно сортируем левую и правую части. 
    4. Объединяем результат: left + root + right 
    """ 
 
    # Базовый случай: если массив пустой или из одного элемента 
    if len(arr) <= 1: 
        return arr 
 
    # Первый элемент считаем корнем 
    root = arr[0] 
 
    # Левый подмассив (элементы меньше корня) 
    left = [] 
    for x in arr[1:]: 
        if x < root: 
            left.append(x) 
 
    # Правый подмассив (элементы больше или равны корню) 
    right = [] 
    for x in arr[1:]: 
        if x >= root: 
            right.append(x) 
 
    # Рекурсивная сортировка и объединение 
    return tree_sort(left) + [root] + tree_sort(right) 
 
 
